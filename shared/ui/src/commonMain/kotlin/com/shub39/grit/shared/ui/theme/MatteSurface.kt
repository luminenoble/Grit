package com.shub39.grit.shared.ui.theme

import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.draw.shadow
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.Shape
import androidx.compose.ui.unit.dp

fun Modifier.matteSurface(shape: Shape, fill: Color, border: Color? = null): Modifier =
    shadow(3.dp, shape)
        .clip(shape)
        .background(fill.copy(alpha = 1f))
        .then(if (border == null) Modifier else Modifier.border(1.dp, border, shape))
